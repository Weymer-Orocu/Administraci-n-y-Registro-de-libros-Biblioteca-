    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        //Extraer el texto que el usuario digitó para buscar
        String criterio = txtBuscar.getText().trim();
        // Si el campo está vacío, asume que quiere ver todos los libros de nuevo
        if (criterio.isEmpty()) {
            jLabel2.setForeground(java.awt.Color.BLACK);
            jLabel2.setText("Campo vacío. Mostrando la lista completa de libros.");
            actualizarTablaVisual(controlador.obtenerTodosLosLibros(), tablaLibros);
            return;
    } 
        // Solicita al controlador que busque la lista principal extrayendo coincidencias del criterio
        java.util.ArrayList<Libros> librosFiltrados = controlador.buscarPorBiblioteca(criterio);
        // Valida si se encontraron libros o si la lista quedó vacía
        if (librosFiltrados.isEmpty()) {
            jLabel2.setForeground(java.awt.Color.RED);
            jLabel2.setText("No se encontraron libros asociados a la biblioteca: '" + criterio + "'.");

        // Limpia la tabla para que no se queden los datos de la búsqueda anterior
        actualizarTablaVisual(librosFiltrados, tablaLibros);
    } else { // Muestra en pantalla los elementos encontrados mediante la búsqueda.
            actualizarTablaVisual(librosFiltrados, tablaLibros);
            jLabel2.setForeground(new java.awt.Color(0, 128, 0)); 
            jLabel2.setText("Búsqueda finalizada. Se encontraron " + librosFiltrados.size() + " coincidencias.");
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnInvertidasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInvertidasActionPerformed
        // TODO add your handling code here:
         java.util.ArrayList<String> unicas = controlador.obtenerBibliotecasUnicas(); // Obtiene una lista con los nombres únicos de las bibliotecas registradas
         javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaInvertidas.getModel(); // Obtiene el modelo de la tabla donde se mostrarán los resultados
         modelo.setRowCount(0); // Limpiar filas anteriores
         // Verifica si no existen bibliotecas registradas
         if (unicas.isEmpty()) {
             jLabel2.setForeground(java.awt.Color.RED);
             jLabel2.setText("No hay libros registrados para extraer bibliotecas.");
             return;         
    }    // Recorre cada nombre de biblioteca obtenido
         for (String b : unicas) {
             // Se ejecuta la inversión de texto puramente recursiva obligatoria
             String textoAlReves = controlador.invertirTextoRecursivo(b);
             modelo.addRow(new Object[]{b, textoAlReves});
    }
         jLabel2.setForeground(new java.awt.Color(0, 128, 0));
         jLabel2.setText("Nombres de bibliotecas invertidos de forma recursiva.");
    }//GEN-LAST:event_btnInvertidasActionPerformed

