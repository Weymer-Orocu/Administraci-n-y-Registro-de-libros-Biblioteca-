    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        // Extrae el texto de las cajas y elimina espacios en blanco sobrantes a los lados (.trim)
        String titulo = txtTitulo.getText().trim(); 
        String autor = txtAutor.getText().trim();
        String fecha = txtFecha.getText().trim();
        String biblioteca = txtBiblioteca.getText().trim();
        // Validación de campos vacíos para evitar errores de datos en las listas
        if (titulo.isEmpty() || autor.isEmpty() || fecha.isEmpty() || biblioteca.isEmpty()) {
        jLabel2.setForeground(java.awt.Color.RED);
        jLabel2.setText("Error: Todos los campos son obligatorios.");
        return;
        }
        try {
        java.util.Date fechaParseada = formatoFecha.parse(fecha); // Transforma la cadena de texto de la fecha
        // Determina si el sistema guarda un registro nuevo o actualiza uno existente
        if (LibroEdicion != null) {
            // Modifica los atributos del objeto localizado en la memoria
            LibroEdicion.setTitulo(titulo);
            LibroEdicion.setAutor(autor);
            LibroEdicion.setFechaPublicacion(fechaParseada);
            LibroEdicion.setBiblioteca(biblioteca);
            jLabel2.setForeground(new java.awt.Color(0, 128, 0));
            jLabel2.setText("Libro editado con éxito.");
            // Limpiamos la variable para salir del modo edición
            LibroEdicion = null; 
            btnRegistrar.setText("Registrar Libro");
        } 
        else { // Solo entra aquí si no habíamos seleccionado nada de la tabla
            int nuevoId = controlador.getListaLibros().size() + 1; // Se genera un nuevo ID tomando la cantidad de libros existentes
            Libros nuevoLibro = new Libros(nuevoId, titulo, autor, fechaParseada, biblioteca); // Se crea un nuevo objeto de tipo Libros con los datos
            controlador.agregarLibro(nuevoLibro);  // Se envía el nuevo libro al controlador para agregarlo a la Lista.            
            jLabel2.setForeground(new java.awt.Color(0, 128, 0));
            jLabel2.setText("Libro registrado con éxito.");
        }
        // Limpia los campos del formulario
        txtTitulo.setText(""); txtAutor.setText(""); txtFecha.setText(""); txtBiblioteca.setText("");
        // Solo actualizamos la tabla de la pestaña 1
        actualizarTablaVisual(controlador.obtenerTodosLosLibros(), jTable1);
        
        } catch (java.text.ParseException e) { // Captura un error se si ingresa una fecha invalida.
        jLabel2.setForeground(java.awt.Color.RED);
        jLabel2.setText("Error: Formato de fecha inválido.");
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void actualizarTablaVisual(java.util.ArrayList<Libros> lista, javax.swing.JTable tablaDestino) {
        // Obtiene el modelo de datos asociado a la tabla destino y permite modificar las filas
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaDestino.getModel();
        modelo.setRowCount(0); // Esto borra las filas anteriores para no duplicar datos
        for (Libros l : lista) { // Recorre cada libro almacenado en la lista recibida.
            modelo.addRow(new Object[]{ // Agrega una nueva fila a la tabla con la información
            l.getId(),  // Agrega el ID único del libro.
            l.getTitulo(), // Agrega el título del libro.
            l.getAutor(), // Agrega el nombre del autor.
            formatoFecha.format(l.getFechaPublicacion()), // Convierte la fecha de publicación al formato ya establecido.
            l.getBiblioteca()
        });
    }
}
