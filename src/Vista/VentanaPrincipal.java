    private void tablaLibrosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaLibrosMouseClicked
        // TODO add your handling code here:
        int filaSeleccionada = tablaLibros.getSelectedRow();  // Obtiene el índice de la fila seleccionada
        // Verifica que exista una fila seleccionada
        if (filaSeleccionada != -1) {
        // Obtener el ID numérico de la fila selecciona 
        int idLibro = Integer.parseInt(tablaLibros.getValueAt(filaSeleccionada, 0).toString());
        LibroEdicion = null;// Inicializa la referencia del libro a editar
         // Recorre la lista original del controlador para encontrar el objeto real
        for (Libros l : controlador.getListaLibros()) { 
            // Comprueba si el ID coincide con el libro seleccionado
            if (l.getId() == idLibro) {
                LibroEdicion = l;  // Guarda la referencia del objeto original para poder modificarlo
                break;
            }
        }
        // Verifica que el libro haya sido encontrad
        if (LibroEdicion != null) {
             // Carga los datos del libro en los campos del formulario
            txtTitulo.setText(LibroEdicion.getTitulo());
            txtAutor.setText(LibroEdicion.getAutor());
            txtFecha.setText(formatoFecha.format(LibroEdicion.getFechaPublicacion()));
            txtBiblioteca.setText(LibroEdicion.getBiblioteca());
            // Cambia el botón a Guardar Cambios
            btnRegistrar.setText("Guardar Cambios");
            // Cambia automáticamente a la pestaña del formulario de edición
            jTabbedPane1.setSelectedIndex(0);
            // Muestra un mensaje informando que el libro está listo para editarse
            jLabel2.setForeground(java.awt.Color.BLUE);
            jLabel2.setText("Editando el Libro ID: " + idLibro + ". Modifique los campos y guarde.");
        } else {
            // Muestra un mensaje de error si no se encontró el objeto original
            jLabel2.setForeground(java.awt.Color.RED);
            jLabel2.setText("Error: No se encontró el objeto original con el ID: " + idLibro);
        }
    }
    }//GEN-LAST:event_tablaLibrosMouseClicked

